import PDFDocument from 'pdfkit';
import QRCode from 'qrcode';
import type { Certificate } from './assets.lifecycle.service.js';

function collect(doc: PDFKit.PDFDocument): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.end();
  });
}

export async function qrPngDataUrl(payload: string): Promise<string> {
  return QRCode.toDataURL(payload, { margin: 1, width: 320, errorCorrectionLevel: 'M' });
}

export async function renderLabelPdf(label: { assetId: string; name: string; assignee: string | null; department: string | null; qrPayload: string }): Promise<Buffer> {
  const doc = new PDFDocument({ size: [226, 300], margin: 16 });
  const qr = await QRCode.toBuffer(label.qrPayload, { margin: 1, width: 400, errorCorrectionLevel: 'M' });
  doc.image(qr, 33, 16, { width: 160 });
  doc.moveDown(0.5).y = 190;
  doc.fontSize(13).font('Helvetica-Bold').text(label.name, 16, 190, { width: 194, align: 'center' });
  doc.fontSize(9).font('Helvetica').fillColor('#555555');
  doc.text(`ID: ${label.assetId}`, { align: 'center' });
  if (label.assignee) doc.text(`Assignee: ${label.assignee}`, { align: 'center' });
  if (label.department) doc.text(`Dept: ${label.department}`, { align: 'center' });
  return collect(doc);
}

export async function renderCertificatePdf(cert: Certificate): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'A4', margin: 56 });
  const left = 56;
  const width = doc.page.width - 112;

  doc.fontSize(20).font('Helvetica-Bold').fillColor('#0b1b3a').text('CERTIFICATE OF DESTRUCTION & SANITIZATION', left, 70, { width, align: 'center' });
  doc.moveDown(0.3).fontSize(9).font('Helvetica-Bold').fillColor('#475569').text('LOCKER ROOM ASSET GOVERNANCE & SECURITY COMPLIANCE', { align: 'center' });
  doc.moveDown(0.3).font('Courier').fontSize(9).text(`Ref: ${cert.reference}`, { align: 'center' });
  doc.moveDown(1.5).font('Helvetica-Oblique').fontSize(10).fillColor('#334155').text(
    'This document certifies that the equipment and digital storage media referenced below have undergone comprehensive sanitization and decommissioning in accordance with NIST SP 800-88 Rev. 1 guidelines.',
    { width, align: 'left' },
  );

  const rows: [string, string][] = [
    ['ASSET IDENTIFIER', cert.assetId],
    ['ASSET DESCRIPTION', cert.assetName],
    ['HARDWARE SERIAL NUMBER', cert.serialNumber ?? '—'],
    ['SANITIZATION DATE', cert.sanitizationDate],
    ['SANITIZATION STANDARD & METHOD', cert.method],
    ['PERFORMED BY TECHNICIAN', cert.wipedBy],
  ];
  doc.moveDown(1.2);
  for (const [k, v] of rows) {
    doc.font('Helvetica-Bold').fontSize(8).fillColor('#64748b').text(k, left, doc.y, { width });
    doc.font('Helvetica').fontSize(11).fillColor('#0b1b3a').text(v, { width });
    doc.moveDown(0.6);
  }
  if (cert.notes) {
    doc.font('Helvetica-Bold').fontSize(8).fillColor('#64748b').text('DISPOSAL NOTES', { width });
    doc.font('Helvetica').fontSize(10).fillColor('#0b1b3a').text(cert.notes, { width });
    doc.moveDown(0.6);
  }
  doc.font('Helvetica-Bold').fontSize(8).fillColor('#2563eb').text('CRYPTOGRAPHIC SANITIZATION VERIFICATION HASH:', { width });
  doc.font('Courier').fontSize(8).fillColor('#0b1b3a').text(`sha256:${cert.verificationHash}`, { width });

  const sigY = doc.page.height - 190;
  doc.moveTo(left, sigY).lineTo(left + 200, sigY).strokeColor('#94a3b8').stroke();
  doc.moveTo(left + width - 200, sigY).lineTo(left + width, sigY).stroke();
  doc.font('Helvetica-Bold').fontSize(10).fillColor('#0b1b3a').text(cert.wipedBy, left, sigY + 6, { width: 200 });
  doc.font('Helvetica').fontSize(7).fillColor('#64748b').text('CERTIFIED DECOMMISSIONING OFFICER', left, sigY + 22, { width: 200 });
  doc.font('Helvetica').fontSize(7).text('WITNESS / INFORMATION SECURITY OFFICER', left + width - 200, sigY + 22, { width: 200 });
  doc.fontSize(7).fillColor('#94a3b8').text(
    'Immutable Governance Record • Generated by Locker Room Platform',
    left, doc.page.height - 90, { width, align: 'center' },
  );
  return collect(doc);
}

/** Simple tabular PDF used for audit-log export. */
export async function renderTablePdf(title: string, headers: string[], rows: string[][]): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 36 });
  const usable = doc.page.width - 72;
  const colW = usable / headers.length;

  const drawRow = (cells: string[], bold = false) => {
    const y = doc.y;
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(8).fillColor('#0b1b3a');
    let maxH = 0;
    cells.forEach((c, i) => {
      const h = doc.heightOfString(c, { width: colW - 6 });
      maxH = Math.max(maxH, h);
      doc.text(c, 36 + i * colW, y, { width: colW - 6 });
    });
    doc.y = y + maxH + 6;
    if (doc.y > doc.page.height - 60) doc.addPage();
  };

  doc.font('Helvetica-Bold').fontSize(14).text(title, { align: 'left' });
  doc.moveDown(0.8);
  drawRow(headers, true);
  doc.moveTo(36, doc.y - 3).lineTo(36 + usable, doc.y - 3).strokeColor('#cbd5e1').stroke();
  for (const r of rows) drawRow(r);
  return collect(doc);
}
